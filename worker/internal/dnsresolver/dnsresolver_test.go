package dnsresolver

import (
	"reflect"
	"strings"
	"testing"
)

func TestParseResolvConf(t *testing.T) {
	conf := `# Generated by Docker Engine.
nameserver 127.0.0.11
options ndots:0
nameserver   2606:4700:4700::1111
nameserver fe80::1%eth0
nameserver not-an-ip
search corp.example
nameserver 127.0.0.11
`
	got := ParseResolvConf(strings.NewReader(conf))
	want := []string{"127.0.0.11:53", "[2606:4700:4700::1111]:53"}
	if !reflect.DeepEqual(got, want) {
		t.Fatalf("ParseResolvConf = %v, want %v", got, want)
	}
}

func TestParseResolvConfEmpty(t *testing.T) {
	if got := ParseResolvConf(strings.NewReader("# nothing\n")); len(got) != 0 {
		t.Fatalf("ParseResolvConf = %v, want none", got)
	}
}

func TestParseOverride(t *testing.T) {
	got, err := ParseOverride(" 10.0.0.2 , 10.0.0.3:5353,::1 ")
	if err != nil {
		t.Fatalf("ParseOverride: %v", err)
	}
	want := []string{"10.0.0.2:53", "10.0.0.3:5353", "[::1]:53"}
	if !reflect.DeepEqual(got, want) {
		t.Fatalf("ParseOverride = %v, want %v", got, want)
	}
}

func TestParseOverrideRejectsNonIP(t *testing.T) {
	for _, bad := range []string{
		"dns.example.com",
		"10.0.0.2:0",
		"10.0.0.2:70000",
		"10.0.0.2 -sr",
		"10.0.0.2;id",
		",",
	} {
		if _, err := ParseOverride(bad); err == nil {
			t.Errorf("ParseOverride(%q) accepted a non-IP resolver", bad)
		}
	}
}

func TestResolveOverrideWins(t *testing.T) {
	got, err := Resolve("10.0.0.2", strings.NewReader("nameserver 127.0.0.11\n"))
	if err != nil {
		t.Fatalf("Resolve: %v", err)
	}
	if !reflect.DeepEqual(got, []string{"10.0.0.2:53"}) {
		t.Fatalf("Resolve = %v, want the override", got)
	}
}

func TestResolveOffDisables(t *testing.T) {
	got, err := Resolve("OFF", strings.NewReader("nameserver 127.0.0.11\n"))
	if err != nil || got != nil {
		t.Fatalf("Resolve(off) = %v, %v; want nil, nil", got, err)
	}
}

func TestResolveFallsBackToResolvConf(t *testing.T) {
	got, err := Resolve("", strings.NewReader("nameserver 127.0.0.11\n"))
	if err != nil {
		t.Fatalf("Resolve: %v", err)
	}
	if !reflect.DeepEqual(got, []string{"127.0.0.11:53"}) {
		t.Fatalf("Resolve = %v, want resolv.conf nameservers", got)
	}
}

func TestResolveNoSource(t *testing.T) {
	got, err := Resolve("", nil)
	if err != nil || got != nil {
		t.Fatalf("Resolve without resolv.conf = %v, %v; want nil, nil", got, err)
	}
}

func TestResolveInvalidOverride(t *testing.T) {
	if _, err := Resolve("dns.example.com", strings.NewReader("nameserver 127.0.0.11\n")); err == nil {
		t.Fatal("Resolve accepted an invalid override")
	}
}

func TestApplyToCommand(t *testing.T) {
	resolvers := []string{"127.0.0.11:53", "[::1]:53"}
	cases := []struct {
		name, in, want string
	}{
		{
			name: "naabu",
			in:   "naabu -host example.com -silent -sr",
			want: "naabu -r 127.0.0.11:53,[::1]:53 -host example.com -silent -sr",
		},
		{
			name: "naabu after a pipe",
			in:   "cat hosts.txt | naabu -silent",
			want: "cat hosts.txt | naabu -r 127.0.0.11:53,[::1]:53 -silent",
		},
		{
			// Discovery keeps the public resolvers: their NXDOMAIN answers carry
			// the SOA that records passive-source names as assets, which
			// Docker's embedded DNS strips.
			name: "dnsx untouched",
			in:   "(echo example.com && subfinder -duc -d example.com) | dnsx -duc -a -resp",
			want: "(echo example.com && subfinder -duc -d example.com) | dnsx -duc -a -resp",
		},
		{
			name: "explicit resolvers are kept",
			in:   "naabu -host example.com -r 9.9.9.9",
			want: "naabu -host example.com -r 9.9.9.9",
		},
		{
			name: "explicit resolvers in one segment do not affect another",
			in:   "naabu -r 9.9.9.9 -l a.txt | naabu -silent",
			want: "naabu -r 9.9.9.9 -l a.txt | naabu -r 127.0.0.11:53,[::1]:53 -silent",
		},
		{
			name: "other tools untouched",
			in:   "httpx -duc -u example.com -resp",
			want: "httpx -duc -u example.com -resp",
		},
		{
			name: "tool name as an argument is not an invocation",
			in:   "echo naabu",
			want: "echo naabu",
		},
		{
			name: "prefixed name is not the tool",
			in:   "mynaabu -host example.com",
			want: "mynaabu -host example.com",
		},
		{
			name: "bare invocation",
			in:   "naabu",
			want: "naabu -r 127.0.0.11:53,[::1]:53",
		},
	}
	for _, tc := range cases {
		t.Run(tc.name, func(t *testing.T) {
			if got := ApplyToCommand(tc.in, resolvers); got != tc.want {
				t.Fatalf("ApplyToCommand(%q)\n got  %q\n want %q", tc.in, got, tc.want)
			}
		})
	}
}

func TestApplyToCommandWithoutResolvers(t *testing.T) {
	in := "naabu -host example.com -silent"
	if got := ApplyToCommand(in, nil); got != in {
		t.Fatalf("ApplyToCommand with no resolvers changed the command: %q", got)
	}
}
